/**
 * The Hermes the iOS shell links: the pinned release's prebuilt xcframework
 * (the static_h line), wrapped in a local Swift package the generated
 * project depends on (src/cli/shells.ts).
 *
 * Meta publishes it to Maven Central as a tarball whose frameworks carry no
 * headers. A remote SwiftPM binary target must be a zip, so it would need a
 * repackaged copy hosted and re-published on every bump; instead the
 * tarball is checked against `iosSha256` (`iosReleaseSha256` for the
 * release variant) in native/hermes.json and unpacked once into a package
 * beside the compiler's cache.
 */
import { createHash } from 'node:crypto';
import { rename, rm, writeFile } from 'node:fs/promises';
import { homedir } from 'node:os';
import { join } from 'node:path';
import type { Profile } from './config.ts';
import { type Digest, download, exists, fillCache, hermes, run, verifyPinned } from './hermesc.ts';

const cache = (name: string) => join(homedir(), '.cache', 'kuito', name);

/**
 * The debug variant has the CDP debugger Chrome DevTools attaches to
 * (docs/devtools.md); the release variant is the optimized VM without it,
 * which native/ios/project.yml matches by defining HERMES_ENABLE_DEBUGGER
 * in Debug only.
 */
export const HERMES_PACKAGES: Record<Profile, string> = {
  debug: cache(`hermes-ios-${hermes.version}`),
  release: cache(`hermes-ios-${hermes.version}-release`),
};

const PINS: Record<Profile, string> = {
  debug: hermes.iosSha256,
  release: hermes.iosReleaseSha256,
};

export function hermesTarball(profile: Profile = 'debug') {
  const { version } = hermes;

  return `https://repo1.maven.org/maven2/com/facebook/hermes/hermes-ios/${version}/hermes-ios-${version}-hermes-ios-${profile}.tar.gz`;
}

/** Unpacked to `include/`, which native/ios/project.yml adds to the header search paths. */
const HEADERS = 'destroot/include';
const XCFRAMEWORK = 'destroot/Library/Frameworks/universal/hermesvm.xcframework';

export const PACKAGE_MANIFEST = `// swift-tools-version: 5.9
// Generated by kuito (src/cli/hermes-ios.ts): the pinned Hermes for iOS.
import PackageDescription

let package = Package(
    name: "HermesEngine",
    platforms: [.iOS(.v16)],
    products: [.library(name: "hermesvm", targets: ["hermesvm"])],
    targets: [.binaryTarget(name: "hermesvm", path: "hermesvm.xcframework")]
)
`;

const SHA256: Digest = {
  name: 'SHA-256',
  of: (bytes) => createHash('sha256').update(bytes).digest('hex'),
};

/** The profile's package directory, downloaded and unpacked on first use. */
export async function hermesPackage(
  profile: Profile = 'debug',
  directory = HERMES_PACKAGES[profile],
  fetchTarball: (url: string) => Promise<Buffer> = (url) => download(url, 'Hermes for iOS'),
) {
  if (await exists(join(directory, 'Package.swift'))) return directory;

  const url = hermesTarball(profile);
  const tarball = verifyPinned(await fetchTarball(url), SHA256, PINS[profile], url);

  await fillCache(directory, async (staging) => {
    const file = join(staging, 'hermes-ios.tar.gz');

    await writeFile(file, tarball);
    await run('tar', ['-xzf', file, '-C', staging]);
    await rename(join(staging, HEADERS), join(staging, 'include'));
    await rename(join(staging, XCFRAMEWORK), join(staging, 'hermesvm.xcframework'));
    await rm(join(staging, 'destroot'), { recursive: true });
    await rm(file);
    await writeFile(join(staging, 'Package.swift'), PACKAGE_MANIFEST);
  });

  return directory;
}
