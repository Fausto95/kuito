/**
 * What the Swift and Kotlin link generators share: the included modules'
 * declared types, once each, and the members the bundle calls.
 */
import type { CatalogModule, LinkedMember, ModuleCatalog } from '../dev/modules/catalog.ts';
import type { FunctionMember, LiveMember, NamedType } from '../dev/modules/spec.ts';

export const GENERATED = (file: string) =>
  `// Generated by kuito from ${file} (docs/native-modules.md). Never edited; rebuilt every build.`;

/**
 * Every type the modules declare. The shell compiles them into one Swift
 * module and one Kotlin package, so two of one name are an error.
 */
export function declaredTypes(modules: readonly CatalogModule[]): NamedType[] {
  const owners = new Map<string, CatalogModule>();

  return modules.flatMap((module) =>
    module.spec.types.map((type) => {
      const earlier = owners.get(type.name);

      if (earlier)
        throw new Error(
          `${type.name} is declared by both ${earlier.path} and ${module.path}: ` +
            'the shell compiles both, so rename one',
        );

      owners.set(type.name, module);

      return type;
    }),
  );
}

/** The members of `modules` the bundle calls, by id. */
export function calledMembers(
  catalog: ModuleCatalog,
  modules: readonly CatalogModule[],
  ids: readonly number[],
): LinkedMember[] {
  const called = new Set(ids);
  const included = new Set(modules.map(({ spec }) => spec));

  return catalog.members.filter(({ id, module }) => called.has(id) && included.has(module));
}

/** Whether a module's `ios` or `android` section asks for a `launch` (docs/native-modules.md#launch). */
export function launches(module: CatalogModule, platform: 'ios' | 'android'): boolean {
  const needs = module.spec.needs[platform];

  return typeof needs === 'object' && needs !== null && Reflect.get(needs, 'launch') === true;
}

/** A module's accessor on the link context: `Battery` → `battery`. */
export const accessorName = (module: string) => module.charAt(0).toLowerCase() + module.slice(1);

/**
 * A string literal's words, for an identifier: `low-power` → `['low', 'power']`,
 * `bestForNavigation` → `['best', 'For', 'Navigation']`.
 */
export const words = (value: string) =>
  value.split(/[^A-Za-z0-9]+|(?<=[a-z0-9])(?=[A-Z])/).filter(Boolean);

/** `hasText` → `HasText`, for `startHasText`. */
export const capitalized = (name: string) => name.charAt(0).toUpperCase() + name.slice(1);

/** A live value's read: a JS-thread function returning it. */
export const liveRead = ({ name, type, line }: LiveMember): FunctionMember => ({
  kind: 'function',
  name,
  thread: 'js',
  callback: false,
  params: [],
  result: type,
  line,
});
